		public void smartBufferCopy(String text) {
			if (text == null || text.isEmpty()) {
				return;
			}

			try {
				String normalizedText = text.replace("\u00A0", " ");
				//AppHandler.toConsole("-------------- normalizedText ------------------\r\n" + normalizedText);

				final String markdownText = convertToMarkdown(normalizedText);
				final String htmlText = convertToHtml(normalizedText);
				//AppHandler.toConsole("-------------- htmlText ------------------\r\n" + htmlText);
				//AppHandler.toConsole("-------------- markdownText ------------------\r\n" + markdownText);
				//AppHandler.toConsole("-------------- -------- ------------------");

				final String windowsHtmlDescription = createDescriptorTemplate(htmlText);
				final DataFlavor htmlFlavor = new DataFlavor("text/html; class=java.lang.String");

				Transferable transferable = new Transferable() {
					@Override
					public DataFlavor[] getTransferDataFlavors() {
						return new DataFlavor[]{htmlFlavor, DataFlavor.stringFlavor};
					}

					@Override
					public boolean isDataFlavorSupported(DataFlavor flavor) {
						return htmlFlavor.equals(flavor) || DataFlavor.stringFlavor.equals(flavor);
					}

					@Override
					public Object getTransferData(DataFlavor flavor) throws UnsupportedFlavorException, IOException {
						if (flavor.equals(DataFlavor.stringFlavor)) {
							return markdownText;
						}
						if (flavor.equals(htmlFlavor)) {
							return windowsHtmlDescription;
						}
						throw new UnsupportedFlavorException(flavor);
					}
				};

				Clipboard clipboard = Toolkit.getDefaultToolkit().getSystemClipboard();
				clipboard.setContents(transferable, null);

			} catch (Exception e) {
				e.printStackTrace();
			}
		}

		private String createDescriptorTemplate(String htmlFragment) {
			String header = """
        Version:0.9
        StartHTML:0000000105
        EndHTML:0000000000
        StartFragment:0000000141
        EndFragment:0000000000
        """;

			String startTag = "<html><body>";
			String endTag = "</body></html>";

			int startFragment = header.length() + startTag.length();
			int endFragment = startFragment + htmlFragment.getBytes(java.nio.charset.StandardCharsets.UTF_8).length;
			int endHTML = endFragment + endTag.length();

			return """
        Version:0.9
        StartHTML:0000000105
        EndHTML:%010d
        StartFragment:%010d
        EndFragment:%010d
        %s%s%s""".formatted(endHTML, startFragment, endFragment, startTag, htmlFragment, endTag);
		}

		private String convertToMarkdown(String text) {
			if (text == null) {
				return "";
			}
			String result = text;

			// 1. Извлекаем <simple_code>
			result = result.replaceAll("(?s)<simple_code[^>]*?>(.*?)</simple_code>", "\n```\n$1\n```\n");

			// 2. Пошагово и надежно разбираем <file_patch> без капризных регулярок
			Pattern patchPattern = Pattern.compile("(?s)<file_patch([^>]*?)>(.*?)</file_patch>");
			Matcher matcher = patchPattern.matcher(result);
			StringBuilder sb = new StringBuilder();
			while (matcher.find()) {
				String attrs = matcher.group(1);
				String code = matcher.group(2);

				String filePath = "Патч";
				// Простой поиск кавычек вокруг пути
				int startQuote = attrs.indexOf("\"");
				int endQuote = attrs.indexOf("\"", startQuote + 1);
				if (startQuote != -1 && endQuote != -1) {
					filePath = attrs.substring(startQuote + 1, endQuote);
					// Убираем протоколы, если они мешают
					filePath = filePath.replace("file:/", "");
				}

				String replacement = "\n\n**Изменения в файле:** `" + filePath + "`\n```diff\n" + code + "\n```\n";
				matcher.appendReplacement(sb, Matcher.quoteReplacement(replacement));
			}
			matcher.appendTail(sb);
			result = sb.toString();

			// 3. Схлопываем стандартные теги
			result = result.replaceAll("(?s)<pre><code>(.*?)</code></pre>", "\n```\n$1\n```\n")
							.replaceAll("(?s)<pre>(.*?)</pre>", "\n```\n$1\n```\n")
							.replaceAll("<code>(.*?)</code>", "`$1`")
							.replaceAll("</?p>", "\n")
							.replaceAll("<br\\s*/?>", "\n")
							.replaceAll("<b>(.*?)</b>", "**$1**")
							.replaceAll("<i>(.*?)</i>", "*$1*")
							.replaceAll("<li>(.*?)</li>", "* $1\n")
							.replaceAll("</?(?:ul|ol)>", "\n");

			result = result.replaceAll("<[^>]*>", "");
			result = result.replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&");

			return result.replaceAll("\n{3,}", "\n\n").trim();
		}

		private String convertToHtml(String text) {
			if (text == null) {
				return "";
			}
			String result = text;

			// Никаких фонов и цветов текста — чистая разметка
			result = result.replaceAll("<code>(.*?)</code>",
							"<code style=\"font-family: monospace; padding: 2px 4px;\">$1</code>");

			result = result.replaceAll("(?s)<simple_code[^>]*?>(.*?)</simple_code>", """
        <pre style="font-family: monospace; padding: 10px; border: 1px solid #d0d7de;"><code>$1</code></pre>
        """);

			// Разбираем <file_patch> по тем же надежным координатам
			Pattern patchPattern = Pattern.compile("(?s)<file_patch([^>]*?)>(.*?)</file_patch>");
			Matcher matcher = patchPattern.matcher(result);
			StringBuilder sb = new StringBuilder();
			while (matcher.find()) {
				String attrs = matcher.group(1);
				String code = matcher.group(2);

				String filePath = "Интерактивный патч";
				int startQuote = attrs.indexOf("\"");
				int endQuote = attrs.indexOf("\"", startQuote + 1);
				if (startQuote != -1 && endQuote != -1) {
					filePath = attrs.substring(startQuote + 1, endQuote);
					filePath = filePath.replace("file:/", "");
				}

				String htmlPatch = """
            <div style="border: 1px solid #d0d7de; margin: 12px 0; font-family: sans-serif;">
                <div style="padding: 6px 12px; font-weight: bold; border-bottom: 1px solid #d0d7de; font-size: 12px;">Файл: %s</div>
                <pre style="font-family: monospace; margin: 0; padding: 10px;"><code>%s</code></pre>
            </div>
            """.formatted(filePath, code);

				matcher.appendReplacement(sb, Matcher.quoteReplacement(htmlPatch));
			}
			matcher.appendTail(sb);

			return sb.toString();
		}

		public void copyToClipboard(String text) {
			if (text == null) {
				return;
			}
			try {
				java.awt.datatransfer.StringSelection selection = new java.awt.datatransfer.StringSelection(text);
				java.awt.datatransfer.Clipboard clipboard = java.awt.Toolkit.getDefaultToolkit().getSystemClipboard();
				clipboard.setContents(selection, selection);
				// AppHandler.toConsole("Текст успешно скопирован в системный буфер.");
			} catch (HeadlessException e) {
				AppHandler.toConsole("Ошибка копирования в буфер Java: " + e.getMessage());
			}
		}

