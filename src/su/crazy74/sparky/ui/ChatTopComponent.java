		@Override
		public void ActivateNode(SessionNode node) {
			//AppHandler.toConsole(" --- ActivateNode");
			// Замещается CurrentNode, а там если что-то есть, идет в History
			if (this.CurrentNode != null && !this.CurrentNode.getBool("interrupted")) {
				this.CurrentNode.set("waitAnswer", false);
				this.CurrentNode.set("success", true);
				this.History.add(this.CleanNode(this.CurrentNode));
				javafx.application.Platform.runLater(() -> {
					this.UpdateNodeUI(this.CurrentNode);
				});
			}
			this.CurrentNode = node;

			node.set("waitAnswer", true);

			this.UpdateNodeUI(node);

			if (this.workerThread != null) {
				this.workerThread.interrupt();
				this.workerThread = null;
			}
			Thread worker = new Thread(() -> {
				BrainHandler.RequestAI(this);
			});
			this.workerThread = worker;
			worker.start();
		}

		public void RetryCurrent(Storage form) {
			if (this.CurrentNode == null) {
				return;
			}
			this.CurrentNode.Remove("error");
			this.CurrentNode.Remove("message");
			this.CurrentNode.Remove("interrupted");
			this.CurrentNode.set("waitAnswer", true);
			if (form != null && form.getStr("ai-model") != null) {
				this.CurrentNode.set("ai-model", form.getStr("ai-model"));
			}
			this.CurrentNode.set("time", java.time.Instant.now().toString());

			this.UpdateNodeUI(this.CurrentNode);

			if (this.workerThread != null) {
				this.workerThread.interrupt();
				this.workerThread = null;
			}
			Thread worker = new Thread(() -> {
				BrainHandler.RequestAI(this);
			});
			this.workerThread = worker;
			worker.start();
		}

