		protected SessionNode CleanNode(SessionNode node) {
			// Отсекаем лишние данные - отдаем JS только то, что реально используется в handler_chat.js
			SessionNode tmpNode = new SessionNode();

			// Собираем чистую копию
			if (node.Exists("guid")) {
				tmpNode.set("guid", node.getStr("guid"));
			}
			if (node.Exists("time")) {
				tmpNode.set("time", node.getStr("time"));
			}
			if (node.Exists("request")) {
				tmpNode.set("request", node.getStr("request"));
			}
			if (node.Exists("answer")) {
				tmpNode.set("answer", node.get("answer")); // JS сам разберет, строка там или объект
			}			//вот тут надо подумать, именно в стадиях может быть много лишнего для UI
			if (node.Exists("stages")) {
				tmpNode.set("stages", node.get("stages"));
			}
			if (node.Exists("waitAnswer")) {
				tmpNode.set("waitAnswer", node.getBool("waitAnswer"));
			}
			if (node.Exists("success")) {
				tmpNode.set("success", node.getBool("success"));
			}
			if (node.Exists("interrupted")) {
				tmpNode.set("interrupted", node.getBool("interrupted"));
			}
			if (node.Exists("system")) {
				tmpNode.set("system", node.get("system"));
			}
			if (node.Exists("error")) {
				tmpNode.set("error", node.get("error"));
			}
			if (node.Exists("metadata")) {
				tmpNode.set("metadata", node.get("metadata"));
			}
			return tmpNode;
		}

		@Override
		public void UpdateNode(SessionNode node) {
			//AppHandler.toConsole(" --- UpdateNode");
			if (node == null || !node.Exists("guid")) {
				return;
			}

			String targetGuid = node.getStr("guid");
			//AppHandler.toConsole(" --- UpdateNode targetGuid: " + targetGuid);

			// 1. Проверяем активную ноду
			if (this.CurrentNode != null && targetGuid.equals(this.CurrentNode.getStr("guid"))) {
				this.CurrentNode.set(node.get());
				this.UpdateNodeUI(this.CurrentNode);
				this.CheckForNotice(this.CurrentNode);

				return;
			}

			// 2. Ищем в истории
			if (this.History != null) {
				for (SessionNode hNode : this.History) {
					if (targetGuid.equals(hNode.getStr("guid"))) {
						hNode.set(node.get());
						this.UpdateNodeUI(hNode);
						return;
					}
				}
			}
		}

		protected void CheckForNotice(SessionNode node) {

			boolean hasError = (node.Exists("error") && node.get("error") != null);
			boolean isSuccess = node.getBool("success");

			/*
			Уведомляем только если итерации полностью завершены (success=true) или произошла фатальная ошибка
			 */
			boolean isNeedNotify = !node.getBool("waitAnswer") && !node.getBool("interrupted") && (isSuccess || hasError);

			if (isNeedNotify) {
				javax.swing.SwingUtilities.invokeLater(() -> {
					/*
					Дальше нам надо проверить, може пользователь сам всё видит
					 */
					AppHandler.toConsole("\r\n\r\n--- invokeLater\r\n");
					AppHandler.toConsole("isNeedNotify: " + isNeedNotify);
					java.awt.Frame mainWindow = WindowManager.getDefault().getMainWindow();
					boolean isIdeActive = mainWindow != null && mainWindow.isActive();
					boolean isChatActive = isIdeActive && (TopComponent.getRegistry().getActivated() == window);

					AppHandler.toConsole("isIdeActive: " + isIdeActive);
					AppHandler.toConsole("isChatActive: " + isChatActive);
					AppHandler.toConsole("hasError: " + hasError);

					if (!isChatActive) {
						//Ну и что именно ему показывать
						if (hasError) {
							AppHandler.toConsole("  --- ChatError on error ");
							SparkyNotifier.ChatError(this);
						} else {
							AppHandler.toConsole("  --- ChatDone on success ");
							SparkyNotifier.ChatDone(this);
						}
					}
					AppHandler.toConsole("\r\n---\r\n\r\n");
				});
			}

		}

